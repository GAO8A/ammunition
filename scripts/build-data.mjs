// Generates src/data/*.ts from the transcribed SAAMI CSVs in data/.
// The CSVs are the source of truth; run `npm run data` after editing them.
import { readFileSync, writeFileSync } from "node:fs";

const SETS = [
  { file: "pistol_cartridges.csv", out: "pistol", type: "Cartridge", category: "pistol", standard: "SAAMI Z299.3-2022" },
  { file: "rifle_cartridges.csv", out: "rifle", type: "Cartridge", category: "rifle", standard: "SAAMI Z299.4-2025" },
  { file: "rimfire_cartridges.csv", out: "rimfire", type: "Cartridge", category: "rimfire", standard: "SAAMI Z299.1-R2026" },
  { file: "shotshells.csv", out: "shotshell", type: "Shotshell", category: "shotshell", standard: "ANSI/SAAMI Z299.2" },
];
const TEXT = new Set(["name", "notes", "issued", "revised", "rim_type", "profile", "gauge", "shell_length", "barrel"]);

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n") { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

for (const set of SETS) {
  const rows = parseCsv(readFileSync(new URL(`../data/${set.file}`, import.meta.url), "utf8"));
  const records = rows.map((r) => {
    const out = { name: r.name, category: set.category, standard: set.standard };
    if ("aliases" in r) out.aliases = r.aliases ? r.aliases.split(";").map((a) => a.trim()) : [];
    for (const [k, v] of Object.entries(r)) {
      if (k === "name" || k === "aliases" || v === "") continue;
      if (TEXT.has(k)) out[camel(k)] = v;
      else {
        const n = Number(v);
        if (!Number.isFinite(n)) throw new Error(`${set.file} ${r.name}: ${k}=${v} is not a number`);
        out[camel(k)] = n;
      }
    }
    return out;
  });
  const src =
    `// Generated by scripts/build-data.mjs from data/${set.file}. Do not edit.\n` +
    `import type { ${set.type} } from "./types.js";\n\n` +
    `export const ${set.out}: readonly ${set.type}[] = ${JSON.stringify(records, null, 1)};\n`;
  writeFileSync(new URL(`../src/data/${set.out}.ts`, import.meta.url), src);
  console.log(`${set.out}: ${records.length} records`);
}
